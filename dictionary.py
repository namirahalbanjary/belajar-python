# list --> array, mengakses data 
# menggunakan index

data_list = ['Amicia', 'Hugo', 'Sophia']

print(data_list[0])  # Output: Amicia

# dictionary (dict) --> associative array
# identifier --> key

data_dict = {
    'key' : 'value',
    'ac' : 'amicia',
    'hg' : 'hugo',
    'sp' : 'sophia',
    'nmbr': 100,
    'list': data_list,
}


print(data_dict['ac'])
print(data_dict['nmbr'])
print(data_dict['list'])