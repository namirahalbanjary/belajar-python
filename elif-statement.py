# ELIF = else if statement

nama = input("Nama kamu siapa? : ")

if nama == "namirah": # kondisi 1
    print("Hai cantik, selamat datang!") # aksi true 1
elif nama == "bana": # kondisi ke 2
    print("hai bana jelek")
elif nama == "nisa":
    print ("hai nisa jelek")
else:
    print("ah kamu siapa")

